def show_welcome():
    print("\n" + "="*50)
    print("🤖 УМНАЯ СИСТЕМА ИИ-ПОМОЩНИКА ЦДЗ (ДЕМО-СТЕНД)")
    print("="*50)
    print("Инструкция:")
    print("1. Введите 'Решить ЦДЗ'")
    print("2. Задайте любой вопрос (например, про стоимость видеокарты или математику)")
    print("="*50)

def local_bot():
    show_welcome()
    while True:
        message = input("\nПользователь (в Telegram): ").strip()
        
        if message.lower() == 'exit':
            print("Бот остановлен.")
            break
            
        elif message.lower() in ['/start', 'help', 'привет']:
            print("\nБот-ассистент: Привет! Я твой ИИ-помощник ЦДЗ. Введи команду 'Решить ЦДЗ', чтобы отправить задание.")
            
        elif "решить цдз" in message.lower() or "🧠" in message:
            print("\nБот-ассистент: 📝 Отправь мне текст вопроса или задачи из ЦДЗ, и я найду решение:")
            task = input("Пользователь присылает текст задачи: ").strip()
            
            if len(task) > 5:
                print("\nБот-ассистент: 🔄 ИИ анализирует текст задания и сверяется с базой знаний...")
                time.sleep(1.2) # Имитация мышления ИИ
                
                # Ищем ключевое слово в тексте вопроса
                found_answer = None
                for key in KNOWLEDGE_BASE:
                    if key in task.lower():
                        found_answer = random.choice(KNOWLEDGE_BASE[key])
                        break
                
                # Если ничего не нашли, берем универсальный ответ
                if not found_answer:
                    found_answer = random.choice(DEFAULT_ANSWERS)
                    
                print(f"\nБот-ассистент:\n{found_answer}")
            else:
                print("\nБот-ассистент: ⚠️ Текст задания слишком короткий.")
        else:
            print("\nБот-ассистент: ⚠️ Неизвестная команда. Введите 'Решить ЦДЗ'.")

if __name__ == '__main__':
    local_bot()
